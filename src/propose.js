// AI proposals for the undecided elements of a mapping.
//
// One call per node kind or relationship type, with its properties. The model
// sees the element, the shape of the whole LPG ontology, the decisions made so
// far and a catalog of the target terms; it answers in JSON whose term fields
// are enums over that catalog, so it cannot name a term the targets do not
// declare. Subjects and value-table IRIs are not asked for: prepare.js derives
// them. Every answer becomes an entry with meta.status: proposed. check() then
// runs on the result; an element with errors gets one repair call with the
// findings, and is dropped if errors remain.
import Ajv2020Module from 'ajv/dist/2020.js';
import { check } from './check.js';
import { indexLpg, defaultDatatype } from './lpg.js';
import { resolve, isActive } from './resolve.js';
import { shorten, parseTemplate, expand } from './iri.js';
import { prepareSubjects, qualifiedSubject, valueTable, TOOL } from './prepare.js';
import { elementNames } from './design.js';

const Ajv2020 = Ajv2020Module.default ?? Ajv2020Module;

export const PROMPT_VERSION = 'propose/3';

const RDFS = 'http://www.w3.org/2000/01/rdf-schema#';
const XSD = 'http://www.w3.org/2001/XMLSchema#';

/** Terms outside the targets that a mapping may use without a target file. */
export const EXTRA_TERMS = [
  { iri: RDFS + 'label', kind: 'datatypeProperty', label: 'label', comment: 'A human-readable name for the subject.' },
  { iri: RDFS + 'comment', kind: 'datatypeProperty', label: 'comment', comment: 'A description of the subject.' },
];
const DATATYPES = ['string', 'boolean', 'integer', 'long', 'int', 'decimal', 'double', 'float', 'date', 'dateTime', 'dateTimeStamp', 'time', 'duration', 'anyURI'].map((t) => XSD + t);
const PREFIX_DEFAULTS = { rdfs: RDFS, xsd: XSD };

const SYSTEM = `You map a labeled property graph (LPG) ontology to RDF target ontologies.
You decide one element at a time: a node kind with its properties, or a relationship type with its properties.
For the element and for each of its listed properties, decide one of:
- map: the target term means what the element states.
- ignore: no target term fits, or the element is bookkeeping, internal to the source system, or computed from other elements. Give the reason.
- defer: the element can be expressed in the target only together with other elements (a join, a pattern spanning several elements). Give the reason.

Rules:
- Use only terms of the catalog. Never invent a term.
- A target term whose meaning is stronger than what the source asserts is a wrong mapping; ignore the element instead.
- A node kind inherits the subject and the classes of the kinds it implies: give only the classes it adds.
- A relationship predicate goes from the start node to the end node; use direction "reverse" when the target property goes from the end node to the start node.
- When the target defines a qualified form for the predicate (a class whose instances stand for one relationship, a property linking the subject to it, and a property from it to the object), give qualified.class, qualified.link and qualified.target, and still give the unqualified predicate: both are emitted. Relationship properties can only be mapped through a qualified resource.
- A property maps to a predicate with a literal value; the datatype defaults from the Neo4j type, give one only to override it. When the values form a small fixed set of codes that stand for individuals in the target model (roles, types), set asIris to true: each value then becomes an IRI. List the values you know in exampleValues.
- IRIs of nodes, qualified resources and values are generated by the tool. Do not provide them.
- confidence: your probability that a careful expert would make the same decision. rationale: one or two sentences.`;

/**
 * @param {object} args
 * @param {object} args.mapping   the mapping to complete; its decided entries are kept
 * @param {object} args.lpgDoc
 * @param {object} args.targets   indexTargets() of the mapping targets
 * @param {object} args.provider  see providers.js
 * @param {string} args.prefix    mapping prefix for generated IRIs (subjects, qualified resources, values)
 * @param {boolean} [args.descriptions=true] send the descriptions of the LPG ontology
 * @param {boolean} [args.openTerms=false]   no enums on terms (to measure invented terms)
 * @param {boolean} [args.repair=true]
 * @param {(q: {section: string, label: string, property: string}) => Promise<string[]|null>} [args.valuesOf]
 *        distinct values of a property, for value tables; the model's examples are used without it
 * @param {string[]} [args.only] element keys (`nodes/<id>`, `relationships/<id>`) to propose for; all by default
 * @param {(event: object) => void} [args.onProgress]
 *
 * Rejected entries are proposed again: the rejected proposal and the
 * reviewer's comment (meta.reviewComment) go into the prompt.
 */
export async function propose({ mapping, lpgDoc, targets, provider, prefix, descriptions = true, openTerms = false, repair = true, valuesOf = null, only = null, spec = null, onProgress = () => {} }) {
  const idx = indexLpg(lpgDoc);
  let m = structuredClone(mapping);
  m.prefixes = { ...m.prefixes };
  for (const [p, ns] of Object.entries(PREFIX_DEFAULTS)) if (!Object.values(m.prefixes).includes(ns) && !m.prefixes[p]) m.prefixes[p] = ns;
  m.nodes ??= {};
  m.relationships ??= {};
  const feedback = takeRejected(m);
  const guide = specGuide(spec, lpgDoc);
  // Out of scope in the spec: left out with its reason, without asking the model. The person accepted it in the spec.
  for (const x of guide.excluded) {
    if (m[x.section][x.id]) continue;
    m[x.section][x.id] = { ignore: { reason: `Out of scope: ${x.reason}` }, meta: { status: 'accepted', proposedBy: { kind: 'tool', name: 'spec' }, rationale: `Spec item ${x.item} (${x.name}), accepted by ${x.reviewedBy ?? 'the reviewer'}.` } };
  }

  const prep = prepareSubjects(m, lpgDoc, { prefix });
  m = prep.mapping;
  const notes = prep.unresolved.map((u) => ({ path: `nodes/${u.node}`, message: u.reason }));

  const catalog = buildCatalog(targets, m.prefixes);
  const completed = [];
  const meta = (a) => ({
    status: 'proposed',
    proposedBy: { kind: 'ai', model: provider.model, promptVersion: PROMPT_VERSION },
    confidence: clamp(a.confidence),
    rationale: a.rationale || '(none given)',
  });
  const calls = [];
  const ctx = { idx, lpgDoc, descriptions, catalog, prefix, valuesOf, meta, notes, completed, feedback, guide };

  // Nodes first, the most general kinds first, so relationships see the classes of their ends.
  const order = [
    ...[...idx.nodes.values()].sort((a, b) => idx.ancestors(a.id).length - idx.ancestors(b.id).length).map((n) => ({ section: 'nodes', id: n.id })),
    ...[...idx.rels.values()].map((r) => ({ section: 'relationships', id: r.id })),
  ].filter((el) => !only || only.includes(`${el.section}/${el.id}`));
  const asked = new Map();
  const repairedInvalid = [];
  for (const el of order) {
    const pending = pendingOf(m, idx, el);
    if (!pending) continue;
    const request = buildRequest(m, ctx, el, pending, { openTerms });
    onProgress({ type: 'call', element: `${el.section}/${el.id}` });
    const key = `${el.section}/${el.id}`;
    let res = await complete(provider, request);
    let answer = validateAnswer(request, res.json, pending);
    calls.push({ element: key, usage: res.usage, answer: res.json, errors: answer.errors });
    // An answer the schema or the rules reject gets one repair call at once, so later elements see the decision.
    if (answer.errors.length && repair) {
      const findings = answer.errors.map((message) => ({ code: 'answer.invalid', path: key, message }));
      onProgress({ type: 'repair', element: key });
      const first = res.json;
      res = await complete(provider, buildRequest(m, ctx, el, pending, { openTerms, previous: first, findings }));
      answer = validateAnswer(request, res.json, pending);
      calls.push({ element: key, repair: true, usage: res.usage, answer: res.json, errors: answer.errors });
      if (!answer.errors.length) repairedInvalid.push({ element: key, findings: ['answer.invalid'], before: first, after: res.json });
    }
    const before = structuredClone(m[el.section][el.id]);
    asked.set(key, { el, pending, request, before, answer: res.json });
    if (answer.errors.length) { notes.push({ path: key, message: `Invalid answer: ${answer.errors.join('; ')}` }); continue; }
    m = await merge(m, ctx, el, pending, answer.answer);
  }

  // Check the result; repair once the elements with errors, then drop what still fails.
  let result = await check({ mapping: m, lpgDoc, targets });
  const repaired = [...repairedInvalid];
  const dropped = [];
  const errorsOf = (r) => {
    const by = new Map();
    for (const f of r.findings.filter((x) => x.severity === 'error')) {
      const key = f.path.split('/').slice(0, 2).join('/');
      if (asked.has(key)) by.set(key, [...(by.get(key) ?? []), f]);
    }
    return by;
  };
  if (repair) {
    for (const [key, findings] of errorsOf(result)) {
      const a = asked.get(key);
      const request = buildRequest(m, ctx, a.el, a.pending, { openTerms, previous: a.answer, findings });
      onProgress({ type: 'repair', element: key });
      const res = await complete(provider, request);
      const answer = validateAnswer(request, res.json, a.pending);
      calls.push({ element: key, repair: true, usage: res.usage, answer: res.json, errors: answer.errors });
      if (answer.errors.length) continue;
      m = restore(m, a.el, a.before);
      m = await merge(m, ctx, a.el, a.pending, answer.answer);
      repaired.push({ element: key, findings: findings.map((f) => f.code), before: a.answer, after: res.json });
    }
    result = await check({ mapping: m, lpgDoc, targets });
  }
  for (const [key, findings] of errorsOf(result)) {
    m = restore(m, asked.get(key).el, asked.get(key).before);
    dropped.push({ element: key, findings: findings.map((f) => `${f.code} ${f.path}: ${f.message}`) });
  }
  if (dropped.length) result = await check({ mapping: m, lpgDoc, targets });

  return { mapping: m, calls, repaired, dropped, notes, subjects: prep.added, completed, result };
}

const rejected = (e) => e?.meta?.status === 'rejected';
const withoutMeta = (e) => JSON.parse(JSON.stringify(e, (k, v) => (k === 'meta' ? undefined : v)));

/** Removes rejected entries from the mapping and returns them by element, with the reviewer's comments. */
function takeRejected(m) {
  const feedback = new Map();
  const add = (key, path, e) => feedback.set(key, [...(feedback.get(key) ?? []), { path, proposal: withoutMeta(e), comment: e.meta.reviewComment ?? null }]);
  for (const section of ['nodes', 'relationships']) {
    for (const [id, e] of Object.entries(m[section])) {
      const key = `${section}/${id}`;
      if (rejected(e)) { add(key, key, e); delete m[section][id]; continue; }
      for (const [pid, pe] of Object.entries(e.properties ?? {})) {
        if (rejected(pe)) { add(key, `${key}/properties/${pid}`, pe); delete e.properties[pid]; }
      }
    }
  }
  return feedback;
}

/**
 * What the accepted items of a spec say to propose: the elements out of scope,
 * and, for one element, the purpose, the principles and the notes about it.
 */
function specGuide(spec, lpgDoc) {
  const accepted = (spec?.items ?? []).filter((i) => i.status === 'accepted');
  if (!accepted.length) return { excluded: [], text: () => '' };
  const names = elementNames(lpgDoc);
  const excluded = accepted.filter((i) => i.kind === 'exclude' && names.get(i.element) && !names.get(i.element).property)
    .map((i) => ({ ...names.get(i.element), name: i.element, reason: i.reason, item: i.id, reviewedBy: i.reviewedBy }));
  const about = (i, el) => { const e = names.get(i.element); return e && e.section === el.section && e.id === el.id; };
  return {
    excluded,
    text(el) {
      const lines = [];
      for (const i of accepted.filter((x) => x.kind === 'purpose')) lines.push(`Purpose: ${i.text}`);
      for (const i of accepted.filter((x) => x.kind === 'principle')) lines.push(`Principle: ${i.text}`);
      for (const i of accepted.filter((x) => x.kind === 'target')) lines.push(`Target: ${i.target}${i.reason ? ` (${i.reason})` : ''}`);
      for (const i of accepted.filter((x) => x.kind === 'include' && about(x, el))) lines.push(`In scope${i.reason ? `: ${i.reason}` : ''}`);
      for (const i of accepted.filter((x) => x.kind === 'note' && about(x, el))) lines.push(`Note on ${i.element}: ${i.text}`);
      return lines.join('\n');
    },
  };
}

/**
 * Asks the provider. A provider that refuses the schema as too large (Gemini:
 * "too many states", when the targets have many terms) gets it without the term
 * lists; the answer is still validated against the full schema, so an invented
 * term is an invalid answer and goes through the repair call.
 */
async function complete(provider, request) {
  try {
    return await provider.complete(request);
  } catch (err) {
    if (!/too many states/i.test(err.message)) throw err;
    const { $defs, ...open } = request.schema;
    const relaxed = JSON.parse(JSON.stringify(open).replace(/\{"\$ref":"#\/\$defs\/[a-z]+"\}/g, '{"type":"string"}'));
    return { ...(await provider.complete({ ...request, schema: relaxed })), relaxed: true };
  }
}

const clamp = (x) => (typeof x === 'number' && x >= 0 && x <= 1 ? x : 0);
const isTool = (e) => e?.meta?.proposedBy?.kind === TOOL.kind;

function restore(m, el, before) {
  const out = structuredClone(m);
  if (before === undefined) delete out[el.section][el.id];
  else out[el.section][el.id] = before;
  return out;
}

/** What is still undecided in an element: the element itself, and properties by id. */
function pendingOf(m, idx, { section, id }) {
  const e = m[section][id];
  if (e?.ignore) return null;
  const self = !e || (isTool(e) && !e.classes);
  const r = resolve(m, idx, isActive);
  let props;
  if (section === 'nodes') {
    const s = r.effectiveSubject(id);
    const inSubject = new Set(s ? parseTemplate(s.template).placeholders : []);
    props = [...idx.nodes.get(id).props.values()].filter((p) => {
      if (e?.properties?.[p.id]) return false;
      if (idx.aliasOf(id, p.id)) return false; // decided with the property it stands for
      if (inSubject.has(p.id)) return false;
      return !idx.ancestors(id).some((a) => m.nodes[a]?.properties?.[p.id]);
    });
  } else {
    props = [...idx.rels.get(id).props.values()].filter((p) => !e?.properties?.[p.id]);
  }
  if (!self && !props.length) return null;
  return { self, props: props.map((p) => p.id) };
}

function buildCatalog(targets, prefixes) {
  const all = [...(targets?.terms() ?? []), ...EXTRA_TERMS];
  const curie = (iri) => shorten(iri, prefixes);
  const isClass = (t) => t.kind === 'class';
  const classes = all.filter(isClass).map((t) => curie(t.iri));
  const properties = all.filter((t) => !isClass(t)).map((t) => curie(t.iri));
  // Between two nodes, only properties that can link resources: not datatype properties.
  const relations = all.filter((t) => !isClass(t) && t.kind !== 'datatypeProperty').map((t) => curie(t.iri));
  const cut = (s, n) => (s && s.length > n ? s.slice(0, n - 1) + '…' : s);
  const lines = all.map((t) => {
    const parts = [`${curie(t.iri)} (${t.kind})`];
    if (t.parents?.length) parts.push(`subOf ${t.parents.map(curie).join(', ')}`);
    if (t.domains?.length) parts.push(`domain ${t.domains.map(curie).join(' | ')}`);
    if (t.ranges?.length) parts.push(`range ${t.ranges.map(curie).join(' | ')}`);
    for (const [p, os] of Object.entries(t.links ?? {})) parts.push(`${curie(p)} ${os.map(curie).join(', ')}`);
    const text = [t.definition, t.comment].filter(Boolean).map((s) => s.replace(/\s+/g, ' ').trim()).join(' ');
    return `- ${parts.join('; ')}${text ? ` — ${cut(text, 320)}` : ''}`;
  });
  // A property whose annotations point to a qualified link property (PROV qualifiedForm) is its unqualified form.
  const unqualified = new Map();
  for (const t of all.filter((x) => !isClass(x))) {
    for (const os of Object.values(t.links ?? {})) {
      for (const o of os) {
        const target = all.find((x) => x.iri === o && !isClass(x));
        if (target) unqualified.set(curie(o), unqualified.has(curie(o)) ? null : curie(t.iri));
      }
    }
  }
  return { classes, properties, relations, datatypes: DATATYPES.map(curie), unqualified, text: lines.join('\n'), size: all.length };
}

function overview(idx) {
  const nodes = [...idx.nodes.values()].map((n) => `${n.label}${n.implied.length ? ` (implies ${n.implied.join(', ')})` : ''}`);
  const rels = [...idx.rels.values()].map((r) => `(${idx.nodes.get(r.from)?.label})-[:${r.type}]->(${idx.nodes.get(r.to)?.label})`);
  return `Node kinds: ${nodes.join('; ')}\nRelationship types: ${rels.join('; ')}`;
}

/** Decisions already in the mapping, element by element, in a few words each. */
export function decisionsText(mapping, lpgDoc) {
  return decisions(mapping, indexLpg(lpgDoc), { all: true });
}

function decisions(m, idx, { all = false } = {}) {
  const r = resolve(m, idx, isActive);
  const lines = [];
  // With all, the reasons too: what a reviewer (or a check against the spec) needs.
  const left = (x) => `${x.deferred ? 'deferred' : 'ignored'}${all && x.reason ? ` (${x.reason})` : ''}`;
  for (const n of idx.nodes.values()) {
    const e = m.nodes[n.id];
    if (e?.ignore) { lines.push(`${n.label}: ${left(e.ignore)}`); continue; }
    const cls = r.effectiveClasses(n.id).map((c) => shorten(c, m.prefixes));
    const props = Object.entries(e?.properties ?? {}).map(([pid, pe]) => `${idx.nodes.get(n.id).props.get(pid)?.name ?? pid} ${pe.ignore ? left(pe.ignore) : `-> ${pe.predicate}`}`);
    if (cls.length || props.length) lines.push(`${n.label}: classes ${cls.join(', ') || 'none'}${props.length ? `; ${props.join(', ')}` : ''}`);
  }
  for (const rel of idx.rels.values()) {
    const e = m.relationships[rel.id];
    if (!e) continue;
    const what = e.ignore ? left(e.ignore)
      : [e.predicate && `-> ${e.predicate}${e.direction === 'reverse' ? ' (reverse)' : ''}`, e.qualified && `qualified ${e.qualified.class}`,
        all && Object.keys(e.properties ?? {}).length ? `properties: ${Object.entries(e.properties).map(([pid, pe]) => `${idx.rels.get(rel.id).props.get(pid)?.name ?? pid} ${pe.ignore ? left(pe.ignore) : `-> ${pe.predicate}`}`).join(', ')}` : null].filter(Boolean).join(', ');
    lines.push(`${rel.type}: ${what}`);
  }
  return lines.join('\n') || '(none yet)';
}

function elementContext(m, ctx, { section, id }, pending) {
  const { idx, descriptions, lpgDoc } = ctx;
  const r = resolve(m, idx, isActive);
  const desc = (o) => (descriptions && o?.description ? { description: o.description } : {});
  const prop = (p, owner, raw) => ({
    id: p.id, name: p.name, type: p.type ?? null,
    required: owner === 'node' ? idx.isRequired(id, p.id) : p.mustExist || (raw?.constraints && Object.values(raw.constraints).some((c) => c.type === 'EXISTS' && c.properties?.includes(p.id))) || false,
    ...(p.oneOf ? { oneOf: p.oneOf } : {}),
    ...desc(raw?.properties?.[p.id]),
  });
  if (section === 'nodes') {
    const n = idx.nodes.get(id);
    const raw = lpgDoc.nodes[id];
    return {
      kind: 'node', id, label: n.label, ...desc(raw),
      implies: n.implied,
      impliedBy: [...idx.nodes.values()].filter((x) => idx.ancestors(x.id).includes(id)).map((x) => x.label),
      inheritedClasses: idx.ancestors(id).flatMap((a) => r.effectiveClasses(a)).map((c) => shorten(c, m.prefixes)),
      relationships: [...idx.rels.values()].filter((x) => x.from === id || x.to === id)
        .map((x) => (x.from === id ? `-[:${x.type}]->(${idx.nodes.get(x.to)?.label})` : `<-[:${x.type}]-(${idx.nodes.get(x.from)?.label})`)),
      decideElement: pending.self,
      properties: pending.props.map((pid) => prop(idx.nodes.get(id).props.get(pid), 'node', raw)),
    };
  }
  const rel = idx.rels.get(id);
  const raw = lpgDoc.relationships[id];
  const end = (nodeId) => ({ label: idx.nodes.get(nodeId)?.label, classes: r.effectiveClasses(nodeId).map((c) => shorten(c, m.prefixes)) });
  const card = (e) => (e?.count != null ? { count: e.count } : e?.max_count != null ? { maxCount: e.max_count } : {});
  return {
    kind: 'relationship', id, type: rel.type, ...desc(raw),
    start: { ...end(rel.from), ...card(raw?.from) }, end: { ...end(rel.to), ...card(raw?.to) },
    decideElement: pending.self,
    properties: pending.props.map((pid) => prop(rel.props.get(pid), 'rel', raw)),
  };
}

/** JSON Schema of the answer for one element. */
function answerSchema(ctx, { section }, pending, { openTerms }) {
  // Gemini compiles the schema into a grammar and refuses large ones: the
  // properties are one array (one copy of the item schema, not one per
  // property), numbers have no bounds (clamp() bounds them), and term lists
  // are shared definitions.
  const term = (def) => (openTerms ? { type: 'string' } : { $ref: `#/$defs/${def}` });
  const decision = { type: 'string', enum: ['map', 'ignore', 'defer'] };
  const common = {
    reason: { type: 'string', description: 'Why the element is ignored or deferred. Empty when mapped.' },
    rationale: { type: 'string' },
    confidence: { type: 'number', description: 'Between 0 and 1.' },
  };
  const propSchema = {
    type: 'object',
    properties: {
      id: { type: 'string', enum: pending.props },
      decision,
      predicate: term('property'),
      datatype: term('datatype'),
      asIris: { type: 'boolean' },
      exampleValues: { type: 'array', items: { type: 'string' } },
      ...common,
    },
    required: ['id', 'decision', 'rationale', 'confidence'],
  };
  const props = { type: 'array', description: 'One item per property of the element, by id.', items: propSchema };
  const self = section === 'nodes'
    ? { decision, classes: { type: 'array', items: term('class') }, ...common }
    : {
      decision,
      predicate: term('relation'),
      direction: { type: 'string', enum: ['forward', 'reverse'] },
      qualified: {
        type: 'object',
        properties: { class: term('class'), link: term('relation'), target: term('relation') },
        required: ['class', 'link', 'target'],
      },
      ...common,
    };
  return {
    type: 'object',
    ...(openTerms ? {} : { $defs: {
      class: { type: 'string', enum: ctx.catalog.classes },
      property: { type: 'string', enum: ctx.catalog.properties },
      relation: { type: 'string', enum: ctx.catalog.relations },
      datatype: { type: 'string', enum: ctx.catalog.datatypes },
    } }),
    properties: { ...(pending.self ? self : {}), ...(pending.props.length ? { properties: props } : {}) },
    required: [...(pending.self ? ['decision', 'rationale', 'confidence'] : []), ...(pending.props.length ? ['properties'] : [])],
  };
}

function buildRequest(m, ctx, el, pending, { openTerms, previous = null, findings = null }) {
  const header = ctx.descriptions && ctx.lpgDoc.description ? `${ctx.lpgDoc.name ?? ctx.lpgDoc.id}: ${ctx.lpgDoc.description}` : `${ctx.lpgDoc.name ?? ctx.lpgDoc.id}`;
  const parts = [
    `# Target catalog (${ctx.catalog.size} terms)\n${ctx.catalog.text}`,
    `# LPG ontology\n${header}\n${overview(ctx.idx)}`,
    ...(ctx.guide.text(el) ? [`# Specification, validated by the person: follow it\n${ctx.guide.text(el)}`] : []),
    `# Decisions so far\n${decisions(m, ctx.idx)}`,
    `# Element to decide\n${JSON.stringify(elementContext(m, ctx, el, pending), null, 1)}`,
  ];
  const fb = ctx.feedback.get(`${el.section}/${el.id}`);
  if (fb) {
    parts.push(`# Reviewer feedback\nA reviewer rejected these proposals for this element. Follow the reasons.\n${fb.map((f) => `- ${f.path}: ${JSON.stringify(f.proposal)}${f.comment ? `\n  Reason: ${f.comment}` : ''}`).join('\n')}`);
  }
  if (previous) {
    parts.push(`# Your previous answer\n${JSON.stringify(previous)}\n\n# The checker rejected it\n${findings.map((f) => `- ${f.code} at ${f.path}: ${f.message}`).join('\n')}\nAnswer again, fixing these errors.`);
  }
  return {
    element: `${el.section}/${el.id}`,
    system: SYSTEM,
    user: parts.join('\n\n'),
    schema: answerSchema(ctx, el, pending, { openTerms }),
  };
}

let ajv;
/**
 * Schema validation, then the rules a schema cannot say. Returns the answer
 * with its properties keyed by id.
 */
function validateAnswer(request, json, pending) {
  ajv ??= new Ajv2020({ allErrors: true, strict: false });
  const errors = [];
  const validate = ajv.compile(request.schema);
  if (!validate(json)) errors.push(...validate.errors.map((e) => `${e.instancePath || '(root)'} ${e.message}`));
  // Models often explain an ignore in the rationale and leave the reason empty: the rationale is then the reason.
  const needReason = (a, path) => {
    if ((a?.decision !== 'ignore' && a?.decision !== 'defer') || a.reason?.trim()) return;
    if (a.rationale?.trim()) a.reason = a.rationale;
    else errors.push(`${path}: ${a.decision} without a reason`);
  };
  if (json && typeof json === 'object') {
    needReason(json, '(element)');
    if (request.element.startsWith('relationships/') && json.decision === 'map' && !json.predicate && !json.qualified) errors.push('(element): map without predicate or qualified');
    const items = Array.isArray(json.properties) ? json.properties : [];
    for (const a of items) {
      needReason(a, a?.id);
      if (a?.decision === 'map' && !a.predicate) errors.push(`${a?.id}: map without predicate`);
    }
    for (const pid of pending.props) {
      const n = items.filter((a) => a?.id === pid).length;
      if (n !== 1) errors.push(`${pid}: ${n ? 'answered several times' : 'no answer'}`);
    }
  }
  const byId = Object.fromEntries((Array.isArray(json?.properties) ? json.properties : []).map(({ id, ...a }) => [id, a]));
  return { errors, answer: { ...json, properties: byId } };
}

async function merge(m, ctx, el, pending, a) {
  const { idx, prefix, valuesOf, meta } = ctx;
  const out = structuredClone(m);
  const section = out[el.section];
  const prev = section[el.id];
  const ignore = (x) => ({ ignore: { reason: x.reason.trim(), ...(x.decision === 'defer' ? { deferred: true } : {}) }, meta: meta(x) });

  let entry;
  if (pending.self && a.decision !== 'map') {
    section[el.id] = ignore(a);
    return out;
  }
  if (pending.self) {
    entry = {};
    if (prev?.subject) entry.subject = prev.subject;
    if (el.section === 'nodes') {
      if (a.classes?.length) entry.classes = [...new Set(a.classes)];
    } else {
      if (a.predicate) entry.predicate = a.predicate;
      if (a.direction === 'reverse') entry.direction = 'reverse';
      if (a.qualified) {
        entry.qualified = { subject: qualifiedSubject(out, ctx.lpgDoc, el.id, a.qualified.class, { prefix }), ...a.qualified };
        // The unqualified predicate, when the model left it out or gave the link instead.
        const plain = ctx.catalog.unqualified.get(a.qualified.link);
        if (plain && (!entry.predicate || entry.predicate === a.qualified.link)) {
          ctx.completed.push({ element: `${el.section}/${el.id}`, predicate: plain, was: entry.predicate ?? null });
          entry.predicate = plain;
        }
      }
    }
    entry.meta = meta(a);
    if (prev?.subject && isTool(prev)) entry.meta.rationale = `${entry.meta.rationale} (Subject: ${prev.meta.rationale})`;
  } else {
    entry = structuredClone(prev);
  }

  const owner = el.section === 'nodes' ? idx.nodes.get(el.id) : idx.rels.get(el.id);
  for (const pid of pending.props) {
    const pa = a.properties?.[pid];
    if (!pa) continue;
    entry.properties ??= {};
    if (pa.decision !== 'map') { entry.properties[pid] = ignore(pa); continue; }
    const prop = owner.props.get(pid);
    const pe = { predicate: pa.predicate };
    if (pa.asIris) {
      const known = valuesOf ? await valuesOf({ section: el.section, label: owner.label ?? owner.type, property: prop.name }) : null;
      const values = known ?? pa.exampleValues ?? [];
      if (values.length) pe.values = valueTable(prop.name, values, { prefix });
      else pe.kind = 'iri';
    } else if (pa.datatype) {
      pe.datatype = pa.datatype;
    }
    pe.meta = meta(pa);
    entry.properties[pid] = pe;
  }
  section[el.id] = entry;
  return out;
}

/** Marks every proposed entry accepted: for evaluating proposals end to end, never for review. */
export function acceptAll(mapping) {
  const out = structuredClone(mapping);
  const walk = (o) => {
    if (!o || typeof o !== 'object') return;
    if (o.meta?.status === 'proposed') o.meta = { ...o.meta, status: 'accepted' };
    for (const v of Object.values(o)) walk(v);
  };
  walk(out.nodes);
  walk(out.relationships);
  return out;
}

export const VARIANTS_FORMAT = 'n20s-propose-variants/0.1';

/**
 * Runs propose several times from the same mapping. The first pass is the
 * proposal; the others say how stable each decision is (a decision that
 * changes between passes deserves a closer review).
 */
export async function proposePasses({ passes = 1, onProgress = () => {}, ...args }) {
  const results = [];
  for (let i = 0; i < passes; i++) {
    results.push(await propose({ ...args, onProgress: (e) => onProgress({ ...e, pass: i + 1 }) }));
  }
  return { ...results[0], passes: results, variants: variantsOf(results.map((r) => r.mapping), args.lpgDoc) };
}

const canonical = (v) => (Array.isArray(v) ? v.map(canonical)
  : v && typeof v === 'object' ? Object.fromEntries(Object.keys(v).sort().filter((k) => k !== 'meta').map((k) => [k, canonical(v[k])])) : v);

/**
 * The proposals of several passes, element by element and property by property.
 * With the LPG ontology, a datatype equal to the default for the Neo4j type does not count as a difference.
 */
export function variantsOf(mappings, lpgDoc = null) {
  const idx = lpgDoc ? indexLpg(lpgDoc) : null;
  const plain = (path, m, e) => {
    if (!idx || !e?.datatype) return e;
    const [section, id, , pid] = path.split('/');
    const prop = section === 'nodes' ? idx.findNodeProperty(id, pid)?.prop : idx.rels.get(id)?.props.get(pid);
    const dt = expand(e.datatype, m.prefixes ?? {}).iri;
    if (!prop || dt !== defaultDatatype(prop.type)) return e;
    const { datatype, ...rest } = e;
    return rest;
  };
  const elements = {};
  // Two passes agree when they decide the same; the wording of a reason does not count.
  const note = (path, i, e) => {
    const entry = e === undefined ? null : canonical(e);
    const key = JSON.stringify(entry?.ignore ? { ignore: { deferred: !!entry.ignore.deferred } } : entry);
    const list = (elements[path] ??= []);
    const v = list.find((x) => x.key === key);
    if (v) v.passes.push(i + 1);
    else list.push({ key, entry, passes: [i + 1] });
  };
  const proposedSomewhere = (get) => mappings.some((m) => get(m)?.meta?.status === 'proposed');
  for (const section of ['nodes', 'relationships']) {
    const ids = new Set(mappings.flatMap((m) => Object.keys(m[section] ?? {})));
    for (const id of ids) {
      if (proposedSomewhere((m) => m[section]?.[id])) {
        mappings.forEach((m, i) => {
          const e = m[section]?.[id];
          note(`${section}/${id}`, i, e && { ...e, properties: undefined });
        });
      }
      const pids = new Set(mappings.flatMap((m) => Object.keys(m[section]?.[id]?.properties ?? {})));
      for (const pid of pids) {
        if (!proposedSomewhere((m) => m[section]?.[id]?.properties?.[pid])) continue;
        mappings.forEach((m, i) => {
          const e = m[section]?.[id];
          // A property of an element left out in this pass is left out with it.
          const path = `${section}/${id}/properties/${pid}`;
          note(path, i, e?.ignore ? { ignore: { reason: '(with its element)' } } : plain(path, m, e?.properties?.[pid]));
        });
      }
    }
  }
  const out = {};
  for (const [path, list] of Object.entries(elements)) {
    out[path] = { stable: list.length === 1, variants: list.sort((a, b) => b.passes.length - a.passes.length).map(({ entry, passes }) => ({ entry, passes })) };
  }
  return { format: VARIANTS_FORMAT, passes: mappings.length, elements: out };
}
