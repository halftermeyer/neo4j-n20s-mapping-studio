#!/usr/bin/env node
// Moves the hand-made lineage mapping and its oracle onto the Aura export of the
// same model (ids n:0, r:0, p:0... instead of entity, used, id...). The results
// are the gold of the propose evaluation:
//   examples/lineage/lineage-prov.aura.mapping.yaml
//   examples/lineage/oracle.aura.yaml
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { rekeyMapping, rekeyOracle } from '../src/rekey.js';

const EXAMPLE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../examples/lineage');
const read = (f) => fs.readFileSync(path.join(EXAMPLE, f), 'utf8');

const fromDoc = JSON.parse(read('data-lineage-ontology.json'));
const toDoc = JSON.parse(read('aura-export.json'));
const { mapping, unmatched } = rekeyMapping(YAML.parse(read('lineage-prov.mapping.yaml')), fromDoc, toDoc);
if (unmatched.length) {
  console.error(`No counterpart in the Aura export: ${unmatched.join(', ')}`);
  process.exit(1);
}
mapping.id = 'lineage-prov-aura';
mapping.lpgOntology.location = 'aura-export.json';

const oracle = rekeyOracle(YAML.parse(read('oracle.yaml')), fromDoc, toDoc);
oracle.mapping = 'lineage-prov.aura.mapping.yaml';

const header = (what) => `# Generated by eval/rekey-gold.js from ${what}: the same decisions,\n# keyed by the ids of the Aura export (aura-export.json). Do not edit; edit\n# the source and run the script again.\n`;
fs.writeFileSync(path.join(EXAMPLE, 'lineage-prov.aura.mapping.yaml'), header('lineage-prov.mapping.yaml') + YAML.stringify(mapping, { lineWidth: 0 }));
fs.writeFileSync(path.join(EXAMPLE, 'oracle.aura.yaml'), header('oracle.yaml') + YAML.stringify(oracle, { lineWidth: 0 }));
console.log('Wrote lineage-prov.aura.mapping.yaml and oracle.aura.yaml.');
